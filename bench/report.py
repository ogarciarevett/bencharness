"""Write RESULTS.md and the README results table from results/trials.jsonl. Never reruns a model."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STORE = ROOT / "results/trials.jsonl"
START, END = "<!-- results:start -->", "<!-- results:end -->"


def fmt(value, digits=4):
    return "n/a" if value is None else f"{value:.{digits}f}"


def table(rows):
    lines = ["| Trial | Task | Harness | Status | Score | Pass | Active s | Model calls | USD est. | Verdict |",
             "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for row in rows:
        for task, entry in row["tasks"].items():
            for harness, r in entry["results"].items():
                passed = {True: "pass", False: "fail"}.get(r.get("pass"), "n/a")
                lines.append(f"| {row['trial']} | {task} | {harness} | {r.get('status')} | {fmt(r.get('score'))} | "
                             f"{passed} | {fmt(r.get('wall_seconds'), 1)} | {r.get('model_calls', 'n/a')} | "
                             f"{fmt(r.get('cost_estimate_usd'))} | {entry['verdict']} |")
    lines += ["", "```", *(row["bench"] for row in rows), "```"]
    return "\n".join(lines)


def write():
    rows = [json.loads(line) for line in STORE.read_text().splitlines()] if STORE.exists() else []
    body = table(rows)
    notes = [f"- **{row['trial']}:** {row['notes']}" for row in rows if row.get("notes")]
    (ROOT / "RESULTS.md").write_text("# Results\n\nGenerated by `python3 -m bench.report` from "
                                     "`results/trials.jsonl`. Do not edit by hand.\n\n" + body + "\n\n"
                                     + "\n".join(notes) + "\n")
    readme = ROOT / "README.md"
    text = readme.read_text()
    if START in text:
        head, rest = text.split(START, 1)
        readme.write_text(head + START + "\n" + body + "\n" + END + rest.split(END, 1)[1])


if __name__ == "__main__":
    write()
